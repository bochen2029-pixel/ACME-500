// The stub judges: a constant and a rule that never reads the record. O16 stands
// them behind the port and requires that neither earns a rung; --judge stands
// them behind a full run, which is the gym's competence sweep at its floor.
struct NullJudge : Judge {
  Proposal read(const Frame& f) override { Proposal p; p.choice = 0; p.signal = 0.f; p.completeness_hat = f.coverage_hat; p.judge_hash = hash(); return p; }
  bool act_coin(int, uint32_t, float) override { return false; }
  uint32_t hash() const override { return 0x4E554C4Cu; }   // 'NULL'
};
struct RulesJudge : Judge {                                  // a coin over the frame's id: a rule that ignores the record
  Proposal read(const Frame& f) override { Proposal p; p.signal = (u01(0x52554C45ULL, 7700, f.oid) < 0.5f) ? 1.2f : -1.2f;
    p.choice = p.signal > 0.f ? 1 : 0; p.completeness_hat = f.coverage_hat; p.judge_hash = hash(); return p; }
  bool act_coin(int cls, uint32_t oid, float p) override { return u01(0x52554C45ULL, 7200 + cls, oid) < p; }
  uint32_t hash() const override { return 0x52554C45u; }   // 'RULE'
};

// mode * 10 + switch, as the HEADER row carries it: world 0 synthetic · 1 fitted · 2 replay · 3 real;
// switch 0 off · 1 shadow · 2 live. ACME is (synthetic, live) by construction.
enum { MODE_SYNTHETIC = 0 };   // the switch enum lives in gate.h (D2)

// D3: the wall value a TICK row carries: 0 in the sim; the battery's dynamic O25
// gives one run a jittered clock and requires every other row identical.
static float wall_for(const Args& a, int d) { return a.wall_jitter ? 100.f * u01(0x57414C4CULL /*'WALL'*/, 9100, (uint32_t)d) : 0.f; }

static void run_human(Run& R, int days, bool chain = true, int from_day = 0, int sw = SW_LIVE, const Args* a = nullptr) {
  R.tape.chaining = chain;
  if (from_day == 0) { R.hs.init(R.w.NC); if (R.L.NC == 0) R.init_ledger(); }
  auto rep = reports_of(R.f);
  if (R.tape.size() == 0) { R.tape.header(MODE_SYNTHETIC, sw, alphabet_hash()); R.L.apply(R.tape.rec.back()); }   // D2: the ledger folds the switch
  for (int d = from_day; d < days; ++d) {
    world_arrive(R.w, R.L, R.tape, (uint32_t)d);    // intake lands
    tick_fold(R.tape, R.L, (uint32_t)d, a ? wall_for(*a, d) : 0.f);   // D0: the clock is a row, and the ledger's day moves with it
    human_day(R.w, R.L, R.f, R.tape, R.hs, rep, (uint32_t)d);
    world_settle(R.w, R.L, R.f, R.tape, (uint32_t)d);
    dump_snapshot(R.tape, R.L, R.f, (uint32_t)d, nullptr, nullptr);
  }
}

static int cmd_sim(const Args& a) {
  Run R; R.f = build_acme(a.n, a.span, a.seed); R.w = world_of(a, a.seed); R.w.demand_scale = a.demand; R.f.writ.exposure_cap = a.exposure_cap;
  g_dump_dir = a.dump;
  std::unique_ptr<TapeFile> file;
  if (a.tape) { file.reset(new TapeFile()); uint8_t genesis[32] = {0};
    if (!file->open_for_append(a.tape, alphabet_hash(), 0, genesis)) { std::fprintf(stderr, "cannot open the tape at %s\n", a.tape); return 3; }
    R.tape.sink = file.get(); }
  rule("ACME CORP, AS IT IS");
  std::printf("  %d seats, span %d, %d layers.  %d IC / %d lead / %d manager / %d director / %d VP / %d C\n",
              R.f.size(), R.f.span, 6, R.f.n_ic, R.f.n_lead, R.f.n_mgr, R.f.n_dir, R.f.n_vp, R.f.n_c);
  std::printf("  payroll $%.1fM.  %d seats do external work, %d exist because the firm has people, %d hold a warrant.\n",
              R.f.payroll() / 1e6, R.f.count_fn(FN_E), R.f.count_fn(FN_ALPHA), R.f.count_fn(FN_WARRANT));
  const double t0 = now_s();
  run_human(R, a.days);
  const double dt = now_s() - t0;
  const ArmResult ar = score_arm(R.L, R.f);

  print_time_ledger(R.hs.time, "THE YEAR");
  rule("WHAT THE FIRM PRODUCED");
  std::printf("  settled %ld obligations in %d days: %.1f%% good, %.1f%% late, %.1f%% wrong\n",
              ar.settled, a.days, 100.0 * ar.good / std::max(1L, ar.settled),
              100.0 * ar.late / std::max(1L, ar.settled), 100.0 * ar.bad / std::max(1L, ar.settled));
  std::printf("  mean cycle %.1f days   deadline breaches %ld (%.1f%%)   still open %zu\n",
              ar.mean_cycle(), ar.breached, 100.0 * ar.breached / std::max(1L, ar.settled), R.L.open_idx.size());
  std::printf("  escalations %llu (%.2f per decision)   meetings held %llu   holds recorded %llu\n",
              (unsigned long long)R.hs.n_escalated, (double)R.hs.n_escalated / std::max<uint64_t>(1, R.hs.n_decided),
              (unsigned long long)R.hs.n_meetings, (unsigned long long)R.hs.n_held);
  std::printf("  writ cost of the outcomes: $%.1fM   backlog at w_unplaced: $%.1fM (%ld open)   total $%.1fM\n",
              ar.writ_cost / 1e6, ar.backlog_cost / 1e6, ar.open_n, ar.total_cost() / 1e6);
  std::printf("\n  tape: %zu rows, chain head %s..., verify %s   (%.1f s, %.0f rows/s)\n",
              R.tape.size(), R.tape.head_hex().substr(0, 16).c_str(),
              R.tape.verify() < 0 ? "OK" : "BROKEN", dt, R.tape.size() / std::max(1e-9, dt));
  print_row_histogram(R.tape);
  if (file) { R.tape.sink = nullptr; file->close(); tape_meta_write(a.tape, "sim", 0, 0, R.tape.size(), R.tape.head, R.tape.size(), a.n, a.span, a.seed, a.demand, a.days, 0, ACME_GATE_HASH, "live"); }
  if (a.dump) dump_write(a.dump, R.tape, R.L, R.f, R.w, nullptr, nullptr, nullptr, nullptr, a.n, a.span, a.seed, a.demand, a.days, 0);
  std::printf("\n  READ THE LEDGER AGAIN. The escalation line is the round trip in its purest form:\n"
              "  every one of those %llu escalations made a manager re-open systems an IC had\n"
              "  already opened, because the manager could not see the IC's screen.\n",
              (unsigned long long)R.hs.n_escalated);
  return 0;
}

