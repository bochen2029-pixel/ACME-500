static Args parse(int argc, char** argv) {
  Args a;
  for (int i = 1; i < argc; ++i) {
    const char* s = argv[i];
    auto next_i = [&](int d) { return (i + 1 < argc) ? atoi(argv[++i]) : d; };
    auto next_f = [&](float d) { return (i + 1 < argc) ? (float)atof(argv[++i]) : d; };
    if (!strncmp(s, "--sim", 5) || !strncmp(s, "--twin", 6) || !strncmp(s, "--automate", 10)
     || !strncmp(s, "--multiverse", 12) || !strncmp(s, "--selftest", 10) || !strcmp(s, "--o31") || !strcmp(s, "--stub-sweep")) a.mode = s;
    else if (!strcmp(s, "--seeds")) a.o31_seeds = next_i(3);
    else if (!strcmp(s, "--at")) a.o31_at = (i + 1 < argc) ? argv[++i] : "g0";
    else if (!strcmp(s, "--shift")) a.o31_shift = next_f(0.f);
    else if (!strcmp(s, "--judge-comp")) a.judge_comp = next_f(-1.f);
    else if (!strcmp(s, "--m-min")) a.m_min = next_i(-1);
    else if (!strcmp(s, "--shift-day")) a.shift_day = next_i(0);
    else if (!strcmp(s, "--shift-mult")) a.shift_mult = next_f(1.f);
    else if (!strcmp(s, "--thin-wrong")) a.thin_wrong = next_f(-1.f);
    else if (!strcmp(s, "--m-calib")) a.m_calib = next_i(-1);
    else if (!strcmp(s, "--days")) a.days = next_i(260);
    else if (!strcmp(s, "--warm")) a.warm = next_i(180);
    else if (!strcmp(s, "--futures")) a.futures = next_i(64);
    else if (!strcmp(s, "--span")) a.span = next_i(7);
    else if (!strcmp(s, "--n")) a.n = next_i(500);
    else if (!strcmp(s, "--lie")) a.lie = next_i(-1);
    else if (!strcmp(s, "--demand")) a.demand = next_f(1.5f);
    else if (!strcmp(s, "--seed")) a.seed = (uint64_t)next_i(20260913);
    else if (!strcmp(s, "--budget")) a.budget = next_i(-1);
    else if (!strcmp(s, "--judge")) a.judge = (i + 1 < argc) ? argv[++i] : "plant";
    else if (!strcmp(s, "--tape")) a.tape = (i + 1 < argc) ? argv[++i] : nullptr;
    else if (!strcmp(s, "--resume")) a.resume = true;
    else if (!strcmp(s, "--ckpt-every")) a.ckpt_every = next_i(10);
    else if (!strcmp(s, "--dump")) a.dump = (i + 1 < argc) ? argv[++i] : nullptr;
    else if (!strcmp(s, "--switch")) { a.sw = (i + 1 < argc) ? argv[++i] : "live"; if (switch_parse(a.sw) < 0) { std::fprintf(stderr, "--switch off|shadow|live|stop\n"); exit(2); } }
    else if (!strcmp(s, "--switch-file")) a.switch_file = (i + 1 < argc) ? argv[++i] : nullptr;
    else if (!strcmp(s, "--pill")) a.pill = (i + 1 < argc) ? argv[++i] : nullptr;
    else if (!strcmp(s, "--shared")) a.shared = true;
    else if (!strcmp(s, "--flip-rate")) a.flip_rate = next_f(0.025f);
    else if (!strcmp(s, "--unresolved")) a.unresolved = next_f(0.f);
    else if (!strcmp(s, "--exposure-cap")) a.exposure_cap = next_f(0.f);
    else if (!strcmp(s, "--check-shared")) a.check_shared = true;
    else if (!strcmp(s, "--quiet")) a.quiet = true;
    else { std::fprintf(stderr, "unknown flag %s\n", s); exit(2); }
  }
  return a;
}
// E0: the world the args describe: the shared fact and the unanswering rate are
// the plant's; the exposure cap is the writ's
static World world_of(const Args& a, uint64_t seed) {
  World w = make_world(seed, a.shared, a.flip_rate, a.unresolved);
  w.shift_day = (uint32_t)std::max(0, a.shift_day); w.shift_mult = a.shift_mult;   // E3: O59's planted shift, off by default
  return w;
}
static double now_s() { return std::chrono::duration<double>(std::chrono::steady_clock::now().time_since_epoch()).count(); }
static void rule(const char* t) { std::printf("\n=== %s ", t); for (int i = (int)strlen(t); i < 66; ++i) std::putchar('='); std::putchar('\n'); }

